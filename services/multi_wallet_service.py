"""
services/multi_wallet_service.py
================================
Multi-wallet system: Fund Wallet + Buy Wallets.

- Fund Wallet: imported by the user (private key)
- Buy Wallets: generated by the bot
"""

import logging
from typing import Optional, List

from cryptography.fernet import Fernet
from solders.keypair import Keypair

from database.sqlite_db import get_db
from utils.config import settings

logger = logging.getLogger(__name__)


def _fernet() -> Fernet:
    return Fernet(settings.WALLET_ENCRYPTION_KEY.encode())


# ──────────────────────────────────────────────────────────────
# Fund Wallet
# ──────────────────────────────────────────────────────────────

async def import_fund_wallet(user_id: int, private_key: str) -> dict:
    """
    Import a Fund Wallet from a private key.
    Accepts base58 or hex private keys.
    Only one active Fund Wallet is allowed per user.
    """
    try:
        # Try to parse the private key
        private_key = private_key.strip()

        if private_key.startswith("["):
            # JSON array format
            import json
            key_bytes = bytes(json.loads(private_key))
            kp = Keypair.from_bytes(key_bytes)
        else:
            # Assume base58
            from solders.keypair import Keypair as SoldersKeypair
            kp = SoldersKeypair.from_base58_string(private_key)

        address = str(kp.pubkey())
        encrypted = _fernet().encrypt(bytes(kp)).decode()

        async with get_db() as db:
            # Deactivate any existing Fund wallet
            await db.execute(
                "UPDATE multi_wallets SET is_active = 0 WHERE user_id = ? AND wallet_type = 'fund'",
                (user_id,)
            )

            # Insert the new one
            await db.execute("""
                INSERT INTO multi_wallets (user_id, wallet_address, encrypted_private_key, wallet_type, label, is_active)
                VALUES (?, ?, ?, 'fund', 'Fund Wallet', 1)
                ON CONFLICT(user_id, wallet_address) DO UPDATE SET
                    encrypted_private_key = excluded.encrypted_private_key,
                    is_active = 1,
                    label = 'Fund Wallet'
            """, (user_id, address, encrypted))
            await db.commit()

        logger.info(f"Fund wallet imported for user {user_id}: {address[:8]}...")
        return {"success": True, "address": address}

    except Exception as e:
        logger.error(f"Failed to import fund wallet for user {user_id}: {e}")
        return {"success": False, "error": str(e)}


async def get_fund_wallet(user_id: int) -> Optional[dict]:
    """Return the active Fund Wallet for a user."""
    async with get_db() as db:
        async with db.execute("""
            SELECT * FROM multi_wallets
            WHERE user_id = ? AND wallet_type = 'fund' AND is_active = 1
            LIMIT 1
        """, (user_id,)) as cur:
            row = await cur.fetchone()
            return dict(row) if row else None


# ──────────────────────────────────────────────────────────────
# Buy Wallets
# ──────────────────────────────────────────────────────────────

async def generate_buy_wallets(user_id: int, count: int = 2) -> List[dict]:
    """
    Generate `count` new Buy Wallets for the user.
    Returns list of {address, label}
    """
    if count < 1 or count > 20:
        raise ValueError("Count must be between 1 and 20")

    created = []

    async with get_db() as db:
        for i in range(count):
            kp = Keypair()
            address = str(kp.pubkey())
            encrypted = _fernet().encrypt(bytes(kp)).decode()
            label = f"Buy Wallet #{i+1}"

            await db.execute("""
                INSERT INTO multi_wallets (user_id, wallet_address, encrypted_private_key, wallet_type, label, is_active)
                VALUES (?, ?, ?, 'buy', ?, 1)
            """, (user_id, address, encrypted, label))

            created.append({"address": address, "label": label})

        await db.commit()

    logger.info(f"Generated {count} buy wallets for user {user_id}")
    return created


async def get_buy_wallets(user_id: int) -> List[dict]:
    """Return all active Buy Wallets for a user."""
    async with get_db() as db:
        async with db.execute("""
            SELECT id, wallet_address, label, created_at
            FROM multi_wallets
            WHERE user_id = ? AND wallet_type = 'buy' AND is_active = 1
            ORDER BY id ASC
        """, (user_id,)) as cur:
            rows = await cur.fetchall()
            return [dict(row) for row in rows]


# ──────────────────────────────────────────────────────────────
# General helpers
# ──────────────────────────────────────────────────────────────

async def list_all_wallets(user_id: int) -> List[dict]:
    """Return all active wallets (Fund + Buy) for a user."""
    async with get_db() as db:
        async with db.execute("""
            SELECT id, wallet_address, wallet_type, label, created_at
            FROM multi_wallets
            WHERE user_id = ? AND is_active = 1
            ORDER BY wallet_type DESC, id ASC
        """, (user_id,)) as cur:
            rows = await cur.fetchall()
            return [dict(row) for row in rows]


async def get_keypair_from_wallet(wallet_row: dict):
    """Decrypt and return a solders Keypair. Never log the result."""
    privkey_bytes = _fernet().decrypt(wallet_row["encrypted_private_key"].encode())
    return Keypair.from_bytes(privkey_bytes)
