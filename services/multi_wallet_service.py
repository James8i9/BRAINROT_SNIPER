"""
services/multi_wallet_service.py
================================
Multi-wallet system: Fund Wallet + Buy Wallets.

- Fund Wallet: imported by the user (private key)
- Buy Wallets: generated by the bot
"""

import logging
from typing import Optional, List

from cryptography.fernet import Fernet
from solders.keypair import Keypair

from database.sqlite_db import get_db
from utils.config import settings

logger = logging.getLogger(__name__)


def _fernet() -> Fernet:
    return Fernet(settings.WALLET_ENCRYPTION_KEY.encode())


# ──────────────────────────────────────────────────────────────
# Fund Wallet
# ──────────────────────────────────────────────────────────────

async def import_fund_wallet(user_id: int, private_key: str) -> dict:
    """
    Import a Fund Wallet from a private key.
    Accepts base58 or hex private keys.
    Only one active Fund Wallet is allowed per user.
    """
    try:
        # Try to parse the private key
        private_key = private_key.strip()

        if private_key.startswith("["):
            # JSON array format
            import json
            key_bytes = bytes(json.loads(private_key))
            kp = Keypair.from_bytes(key_bytes)
        else:
            # Assume base58
            from solders.keypair import Keypair as SoldersKeypair
            kp = SoldersKeypair.from_base58_string(private_key)

        address = str(kp.pubkey())
        encrypted = _fernet().encrypt(bytes(kp)).decode()

        async with get_db() as db:
            # Deactivate any existing Fund wallet
            await db.execute(
                "UPDATE multi_wallets SET is_active = 0 WHERE user_id = ? AND wallet_type = 'fund'",
                (user_id,)
            )

            # Insert the new one
            await db.execute("""
                INSERT INTO multi_wallets (user_id, wallet_address, encrypted_private_key, wallet_type, label, is_active)
                VALUES (?, ?, ?, 'fund', 'Fund Wallet', 1)
                ON CONFLICT(user_id, wallet_address) DO UPDATE SET
                    encrypted_private_key = excluded.encrypted_private_key,
                    is_active = 1,
                    label = 'Fund Wallet'
            """, (user_id, address, encrypted))
            await db.commit()

        logger.info(f"Fund wallet imported for user {user_id}: {address[:8]}...")
        return {"success": True, "address": address}

    except Exception as e:
        logger.error(f"Failed to import fund wallet for user {user_id}: {e}")
        return {"success": False, "error": str(e)}


async def get_fund_wallet(user_id: int) -> Optional[dict]:
    """Return the active Fund Wallet for a user."""
    async with get_db() as db:
        async with db.execute("""
            SELECT * FROM multi_wallets
            WHERE user_id = ? AND wallet_type = 'fund' AND is_active = 1
            LIMIT 1
        """, (user_id,)) as cur:
            row = await cur.fetchone()
            return dict(row) if row else None


# ──────────────────────────────────────────────────────────────
# Buy Wallets
# ──────────────────────────────────────────────────────────────

async def generate_buy_wallets(user_id: int, count: int = 2) -> List[dict]:
    """
    Generate `count` new Buy Wallets for the user.
    Returns list of {address, label}
    """
    if count < 1 or count > 20:
        raise ValueError("Count must be between 1 and 20")

    created = []

    async with get_db() as db:
        for i in range(count):
            kp = Keypair()
            address = str(kp.pubkey())
            encrypted = _fernet().encrypt(bytes(kp)).decode()
            label = f"Buy Wallet #{i+1}"

            await db.execute("""
                INSERT INTO multi_wallets (user_id, wallet_address, encrypted_private_key, wallet_type, label, is_active)
                VALUES (?, ?, ?, 'buy', ?, 1)
            """, (user_id, address, encrypted, label))

            created.append({"address": address, "label": label})

        await db.commit()

    logger.info(f"Generated {count} buy wallets for user {user_id}")
    return created


async def get_buy_wallets(user_id: int) -> List[dict]:
    """Return all active Buy Wallets for a user."""
    async with get_db() as db:
        async with db.execute("""
            SELECT id, wallet_address, label, created_at
            FROM multi_wallets
            WHERE user_id = ? AND wallet_type = 'buy' AND is_active = 1
            ORDER BY id ASC
        """, (user_id,)) as cur:
            rows = await cur.fetchall()
            return [dict(row) for row in rows]


# ──────────────────────────────────────────────────────────────
# General helpers
# ──────────────────────────────────────────────────────────────

async def list_all_wallets(user_id: int) -> List[dict]:
    """Return all active wallets (Fund + Buy) for a user."""
    async with get_db() as db:
        async with db.execute("""
            SELECT id, wallet_address, wallet_type, label, created_at
            FROM multi_wallets
            WHERE user_id = ? AND is_active = 1
            ORDER BY wallet_type DESC, id ASC
        """, (user_id,)) as cur:
            rows = await cur.fetchall()
            return [dict(row) for row in rows]


async def get_keypair_from_wallet(wallet_row: dict):
    """Decrypt and return a solders Keypair. Never log the result."""
    privkey_bytes = _fernet().decrypt(wallet_row["encrypted_private_key"].encode())
    return Keypair.from_bytes(privkey_bytes)

# ──────────────────────────────────────────────────────────────
# SOL Distribution
# ──────────────────────────────────────────────────────────────

async def distribute_sol(user_id: int, amount_each: float) -> dict:
    """
    Send `amount_each` SOL from the Fund Wallet to every active Buy Wallet.
    Returns {"success": bool, "signature": str|None, "error": str|None, "total_sent": float}
    """
    import aiohttp
    import base64
    from solders.pubkey import Pubkey
    from solders.system_program import transfer, TransferParams
    from solders.transaction import Transaction
    from solders.message import Message
    from solders.hash import Hash
    from utils.config import get_rpc_url

    NETWORK_FEE_RESERVE = 0.00001  # safety buffer per transaction

    fund = await get_fund_wallet(user_id)
    if not fund:
        return {"success": False, "signature": None, "error": "No Fund Wallet found. Import one first.", "total_sent": 0}

    buy_wallets = await get_buy_wallets(user_id)
    if not buy_wallets:
        return {"success": False, "signature": None, "error": "No Buy Wallets found. Generate some first.", "total_sent": 0}

    if amount_each <= 0:
        return {"success": False, "signature": None, "error": "Amount must be greater than 0.", "total_sent": 0}

    total_needed = amount_each * len(buy_wallets) + NETWORK_FEE_RESERVE

    # Get Fund Wallet balance
    from services.bot_wallet_service import get_sol_balance, get_latest_blockhash
    balance = await get_sol_balance(fund["wallet_address"])
    if balance is None:
        return {"success": False, "signature": None, "error": "Could not fetch Fund Wallet balance.", "total_sent": 0}

    if balance < total_needed:
        return {
            "success": False,
            "signature": None,
            "error": f"Insufficient balance. Need {total_needed:.6f} SOL, have {balance:.6f} SOL.",
            "total_sent": 0,
        }

    # Decrypt Fund Wallet keypair
    keypair = await get_keypair_from_wallet(fund)

    blockhash_str = await get_latest_blockhash()
    if not blockhash_str:
        return {"success": False, "signature": None, "error": "Could not fetch blockhash.", "total_sent": 0}

    try:
        instructions = []
        lamports_each = int(amount_each * 1_000_000_000)

        for w in buy_wallets:
            ix = transfer(TransferParams(
                from_pubkey=keypair.pubkey(),
                to_pubkey=Pubkey.from_string(w["wallet_address"]),
                lamports=lamports_each,
            ))
            instructions.append(ix)

        msg = Message.new_with_blockhash(instructions, keypair.pubkey(), Hash.from_string(blockhash_str))
        tx = Transaction([keypair], msg, Hash.from_string(blockhash_str))
        raw = bytes(tx)
    except Exception as e:
        logger.error(f"distribute_sol build tx failed: {e}")
        return {"success": False, "signature": None, "error": f"Failed to build transaction: {e}", "total_sent": 0}

    # Send transaction
    encoded = base64.b64encode(raw).decode()
    try:
        async with aiohttp.ClientSession() as session:
            async with session.post(
                get_rpc_url(),
                json={
                    "jsonrpc": "2.0",
                    "id": 1,
                    "method": "sendTransaction",
                    "params": [encoded, {"encoding": "base64", "skipPreflight": False, "maxRetries": 5}],
                },
                headers={"Content-Type": "application/json"},
                timeout=aiohttp.ClientTimeout(total=30),
            ) as resp:
                data = await resp.json(content_type=None)
                if "error" in data:
                    return {"success": False, "signature": None, "error": str(data["error"]), "total_sent": 0}

                sig = data.get("result")
                total_sent = amount_each * len(buy_wallets)
                logger.info(f"Distributed {total_sent} SOL to {len(buy_wallets)} wallets. tx={sig}")
                return {
                    "success": True,
                    "signature": sig,
                    "error": None,
                    "total_sent": total_sent,
                    "count": len(buy_wallets),
                    "amount_each": amount_each,
                }
    except Exception as e:
        logger.error(f"distribute_sol send failed: {e}")
        return {"success": False, "signature": None, "error": str(e), "total_sent": 0}
